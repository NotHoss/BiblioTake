<article id="chi-siamo">
    <h2>Chi siamo</h2>

    <section id="presentazione">
        <h3>Il progetto BiblioTake</h3>
        <p>
            BiblioTake è un sistema di gestione bibliotecaria sviluppato nell'ambito del corso di
            Tecnologie Web dell'Università degli Studi di Padova (<abbr title="Università degli Studi di Padova">UNIPD</abbr>),
            anno accademico 2025/2026.
        </p>
        <p>
            Il sistema permette di consultare il catalogo della biblioteca, richiedere prestiti e
            lasciare recensioni sui libri letti.
        </p>
    </section>

    <section id="servizi">
        <h3>Cosa puoi fare</h3>
        <ul>
            <li>Consultare il catalogo completo dei libri disponibili</li>
            <li>Cercare libri per titolo, autore o categoria</li>
            <li>Richiedere un prestito dopo aver effettuato l'accesso</li>
            <li>Leggere e scrivere recensioni sui libri</li>
        </ul>
    </section>
</article>
